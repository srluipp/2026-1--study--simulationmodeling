using DifferentialEquations, Plots

# Параметры
β = 0.02
c = 5.0
tspan = (0.0, 100.0)
u0 = [990.0, 10.0, 0.0]  # S, I, R
T_rec = 10.0              # Время выздоровления (10 дней)

# Модифицированная функция для работы с кусочной логикой
function sir_deterministic!(du, u, p, t)
    S, I, R = u
    β, c, T_rec = p

    # Логика до и после 10 дней
    if t < T_rec
        # В первые 10 дней: стандартное распространение без выздоровления
        du[1] = -β * c * S * I / 1000
        du[2] = β * c * S * I / 1000
        du[3] = 0.0
    else
        # После 10 дней: все больные переходят в R за один шаг
        du[1] = -β * c * S * I / 1000  # Новые заболевания продолжаются (если есть I)
        du[2] = 0.0                    # Больные не накапливаются (выздоравливают сразу)
        du[3] = I                      # Восстановление всех текущих больных
    end
end

# Задача с кусочным решением
prob_det = ODEProblem(sir_deterministic!, u0, tspan, (β, c, T_rec))
sol_det = solve(prob_det, Tsit5(), saveat=0.5)

# Визуализация с сохранением в PNG
plot(sol_det,
     labels=["S (восприимчивые)" "I (инфицированные)" "R (выздоровевшие)"],
     title="Детерминированное выздоровление через 10 дней (кусочная модель)",
     xlabel="Время (дней)", ylabel="Количество людей",
     linewidth=2, legend=:topright, dpi=300)

# Сохраняем график в файл PNG
savefig("sir_det_coupled.png")  # Файл сохранится в текущей папке














